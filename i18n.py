def _(key, lang=None):
    """Retorna la traducción según el idioma (Streamlit o Manual)"""
    if not lang:
        try:
            import streamlit as st
            lang = st.session_state.get('language', 'es')
        except:
            lang = 'es' # Default si falla streamlit
    return TRANSLATIONS.get(key, {}).get(lang, key)
